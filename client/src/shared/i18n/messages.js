export function translate(key, locale = "en", values = {}) {
  if (key == null) return "";
  const lookup = (messages) =>
    Object.prototype.hasOwnProperty.call(messages, key) ? messages[key] : undefined;
  let message = (locale === "ru" ? lookup(ru) : undefined) ?? lookup(en) ?? key;
  if (typeof message === "object")
    message =
      message[new Intl.PluralRules(locale).select(Number(values.count || 0))] || message.other;
  return String(message).replace(/\{(\w+)\}/g, (match, name) =>
    values[name] === undefined ? match : String(values[name]),
  );
}
